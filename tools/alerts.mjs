export function renderTokenPage(kind) {
  const confirm = kind === "confirm";
  const title = confirm ? "Confirm OutageRadar alerts" : "Stop OutageRadar alerts";
  const lede = confirm
    ? "Press the button to start alerts in the channel that received our message. Opening this page alone does nothing."
    : "Press the button to stop all OutageRadar alerts to the channel that received them. Opening this page alone does nothing.";
  return `${head(title + " | OutageRadar")}
<body data-alerts="${confirm ? "confirm" : "unsubscribe"}">
<div class="wrap">
  ${TOP}
  <h1 class="page-h1">${esc(title)}</h1>
  <p class="lede">${lede}</p>
  <p><button type="button" id="go" hidden>${confirm ? "Confirm alerts" : "Unsubscribe"}</button></p>
  <p id="status" role="status" aria-live="polite"></p>
  <noscript><p>This page needs JavaScript. You can also email <a href="mailto:contact@liveoutageradar.com">contact@liveoutageradar.com</a>.</p></noscript>
  ${FOOTER}
</div>
<script type="module" src="/alerts.js"></script>
</body>
</html>
`;
}
